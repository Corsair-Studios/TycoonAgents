/** The agent definition embedded in a capability pack. */
export interface PackAgent {
  /** Agent id, used as the `.claude/agents/<id>.md` file name. */
  id: string;
  /** Display name, rendered as the markdown H1 heading. */
  name: string;
  /** Model id written to YAML frontmatter (`model:`). */
  model: string;
  /** One-line role description for the `## Role` section. */
  role: string;
  /** Pipe-delimited task-routing keywords for the `## Keywords` section. */
  keywords: string;
  /**
   * Optional roster tier. Omitted (undefined) for regular worker agents.
   * `"lead"` marks a team-lead coordinator that owns a set of worker
   * agents — installers and the ready-test skill must not treat lead
   * agents the same as regular workers (see `LEAD_AGENTS`). `"reviewer"`
   * marks the optional Review-pass agent (see `REVIEWER_AGENTS`) — it IS a
   * normal spawnable leaf worker (unlike a lead, it owns no team), the tier
   * exists only so install/remove can safely identify TycoonAgents-owned
   * `reviewer.md` files the same way lead removal does for `tier: lead`.
   */
  tier?: "lead" | "reviewer";
}

/**
 * Build the markdown content for a pack's domain agent file
 * (`.claude/agents/<id>.md`). Pure: no fs/vscode access, so this is
 * unit-testable. Output round-trips through `parseAgentMarkdown`.
 * Returns a string ending in a trailing newline.
 *
 * Regular agents (no `tier`) render exactly as before — a `model:`
 * frontmatter line only. Lead agents additionally emit a `tier: lead`
 * frontmatter line so downstream tooling (installers, the ready-test
 * skill) can recognize and skip them.
 *
 * `packId`, when supplied, additionally emits a `tycoon_pack: <packId>`
 * frontmatter line — a provenance marker recording that this file was
 * generated by TycoonAgents' pack installer for that pack (e.g. `"uefn"`).
 * `_handleInstallPack` (panel.ts) uses this marker via
 * {@link agentMarkdownHasTycoonMarker} to tell "ours, safe to refresh"
 * apart from "a legacy/foreign file that happens to share this id" before
 * overwriting an existing agent file. Frontmatter key order is fixed:
 * `name`, `description`, then `model`, then `tier` (if any), then
 * `tycoon_pack` (if any) — deterministic, no incidental churn.
 *
 * `name` and `description` are REQUIRED by Claude Code to register a
 * subagent (https://docs.claude.com/ ... subagents) — without them a
 * generated `.claude/agents/<id>.md` file is never registered, so
 * `subagent_type` can never spawn it. `name` is always `agent.id` (the
 * kebab-case slug Claude Code requires — NOT `agent.name`, which is a
 * Title Case display string like "Verse Expert"). `description` is
 * `agent.role` (falling back to `agent.name` if `role` is ever empty),
 * JSON-stringified so colons/quotes/newlines in free-text role prose can
 * never break the YAML frontmatter block.
 */

/**
 * The `## Working discipline` body appended to every NON-orchestrator agent's
 * generated markdown. Reinforces that workers/reviewers are LEAVES: they do
 * the work themselves, never spawn nested Task sub-agents (which the Claude
 * Code harness does not make block on their children — a nested spawn returns
 * premature "I'll report when it's done" narration with no writes), and never
 * return that narration as a result. Shared with
 * {@link resyncAgentDisciplineSection} so fresh installs and on-load resyncs
 * stay byte-identical.
 */
export const WORKING_DISCIPLINE_BODY =
  "- You are a LEAF: do the assigned task YOURSELF — reads, searches, and edits — with your own tools. Do NOT spawn Task or sub-agents; there is no delegation below you.\n" +
  "- BLOCK until the work is actually finished. Never end with a \"running in the background\", \"I'll report when it's done\", or \"waiting for another agent\" message — that is not a valid result. Return only once the files are written and verified.\n" +
  "- Report the concrete outcome in under 250 words: what changed (file:line), how you verified it, and any open issues.";

export function buildAgentMarkdown(agent: {
  id: string;
  name: string;
  model: string;
  role: string;
  keywords: string;
  tier?: "lead" | "reviewer";
}, packId?: string): string {
  const description = agent.role && agent.role.trim() !== "" ? agent.role : agent.name;
  return (
    "---\n" +
    `name: ${agent.id}\n` +
    `description: ${JSON.stringify(description)}\n` +
    `model: ${agent.model}\n` +
    // Config-level enforcement of the leaf-worker rule: the prose-only
    // "Working discipline" section below could be ignored, so every
    // non-orchestrator agent also gets a first-class denylist on the
    // sub-agent-spawning tool (named `Agent` since Claude Code v2.1.63).
    (agent.id !== "orchestrator" ? "disallowedTools: Agent\n" : "") +
    (agent.tier ? `tier: ${agent.tier}\n` : "") +
    (packId ? `tycoon_pack: ${packId}\n` : "") +
    "---\n" +
    "\n" +
    `# ${agent.name}\n` +
    "\n" +
    "## Role\n" +
    `${agent.role}\n` +
    "\n" +
    "## Keywords (for task routing)\n" +
    `${agent.keywords}\n` +
    // Leaf-worker discipline on every agent EXCEPT the orchestrator (the only
    // agent that is meant to delegate). Kept as the trailing section so the
    // on-load resync can find/append it deterministically.
    (agent.id !== "orchestrator"
      ? "\n## Working discipline\n" + WORKING_DISCIPLINE_BODY + "\n"
      : "")
  );
}

/**
 * Detect TycoonAgents' `tycoon_pack:` provenance marker in an existing
 * agent `.md` file's frontmatter text. Pure (no fs/vscode access), inverse
 * of the `tycoon_pack` line {@link buildAgentMarkdown} writes when given a
 * `packId`. Used by `_handleInstallPack` to distinguish "this file was
 * written by our installer (safe to refresh in place)" from "this file is
 * a legacy/foreign same-named agent (back it up before replacing)".
 */
export function agentMarkdownHasTycoonMarker(content: string): boolean {
  const lines = content.split(/\r\n|\n/);
  if (lines.length === 0 || lines[0] !== "---") {
    return false;
  }
  for (let i = 1; i < lines.length; i++) {
    if (lines[i] === "---") {
      break;
    }
    if (/^\s*tycoon_pack\s*:\s*\S+\s*$/.test(lines[i])) {
      return true;
    }
  }
  return false;
}

/**
 * Read the `tier:` frontmatter value from an agent markdown file's content,
 * if any. Pure (no fs/vscode access), inverse of the `tier` line
 * {@link buildAgentMarkdown} writes. This is the safety predicate used
 * before deleting a `.claude/agents/<id>.md` file when downgrading out of
 * Team Leads mode: only a file whose frontmatter says `tier: lead` is
 * eligible for removal, so a user's own file that happens to share an id
 * like `build-lead.md` (but wasn't written by TycoonAgents) is never
 * deleted.
 */
export function agentMarkdownTier(content: string): string | undefined {
  const lines = content.split(/\r\n|\n/);
  if (lines.length === 0 || lines[0] !== "---") {
    return undefined;
  }
  for (let i = 1; i < lines.length; i++) {
    if (lines[i] === "---") {
      break;
    }
    const match = /^\s*tier\s*:\s*(\S+)\s*$/.exec(lines[i]);
    if (match) {
      return match[1];
    }
  }
  return undefined;
}

/**
 * Secondary "is this file ours" signal for regular worker agents installed
 * before buildAgentMarkdown was passed a packId (so they predate the
 * tycoon_pack marker). Considers a file a positive match for `agent` only
 * if its frontmatter `model:` line equals `agent.model` AND its
 * `## Keywords (for task routing)` section body equals `agent.keywords`
 * exactly — keywords are a distinctive pipe-delimited fingerprint a user
 * is very unlikely to have hand-authored identically, so this is safe
 * without requiring the marker. Used only as a fallback alongside
 * agentMarkdownHasTycoonMarker, never as the sole signal for anything
 * destructive beyond a Role-section text swap.
 */
export function workerAgentFingerprintMatches(content: string, agent: PackAgent): boolean {
  const lines = content.split(/\r\n|\n/);
  if (lines.length === 0 || lines[0] !== "---") {
    return false;
  }
  let modelMatches = false;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i] === "---") {
      break;
    }
    const match = /^\s*model\s*:\s*(\S+)\s*$/.exec(lines[i]);
    if (match) {
      modelMatches = match[1] === agent.model;
      break;
    }
  }
  if (!modelMatches) {
    return false;
  }

  const heading = "## Keywords (for task routing)\n";
  const headingIdx = content.indexOf(heading);
  if (headingIdx === -1) {
    return false;
  }
  const rest = content.slice(headingIdx + heading.length);
  const lineEnd = rest.indexOf("\n");
  const keywordsLine = lineEnd === -1 ? rest : rest.slice(0, lineEnd);
  return keywordsLine.trim() === agent.keywords;
}

/**
 * Surgically replace the `## Role` section body in an agent markdown file
 * with `newRole`, preserving frontmatter and every other section
 * byte-for-byte. Returns the updated content, or the input content
 * unchanged if the current Role text already equals newRole, or `null` if
 * no `## Role\n...\n\n##` section shape is found (never touch a file whose
 * shape we don't recognize). Inverse-adjacent to buildAgentMarkdown's exact
 * output shape: `"## Role\n" + role + "\n\n" + "## Keywords ..."`.
 */
export function resyncAgentRoleSection(content: string, newRole: string): string | null {
  const heading = "## Role\n";
  const headingIdx = content.indexOf(heading);
  if (headingIdx === -1) {
    return null;
  }
  const bodyStart = headingIdx + heading.length;
  const rest = content.slice(bodyStart);

  const blankLineIdx = rest.indexOf("\n\n");
  const nextHeadingMatch = /\n## /.exec(rest);
  const nextHeadingIdx = nextHeadingMatch ? nextHeadingMatch.index : -1;

  let bodyEnd = rest.length;
  if (blankLineIdx !== -1) {
    bodyEnd = blankLineIdx;
  }
  if (nextHeadingIdx !== -1 && nextHeadingIdx < bodyEnd) {
    bodyEnd = nextHeadingIdx;
  }

  const currentBody = rest.slice(0, bodyEnd);
  if (currentBody === newRole) {
    return content;
  }

  return content.slice(0, bodyStart) + newRole + rest.slice(bodyEnd);
}

/**
 * Ensure a managed worker agent file carries the current `## Working
 * discipline` section (see {@link WORKING_DISCIPLINE_BODY}). This section is
 * the LAST section by construction, so it spans from its heading to end of
 * file. Behavior:
 *  - present and current → returns the input content unchanged (idempotent);
 *  - present but stale → replaces heading→EOF with the canonical section;
 *  - ABSENT (file installed before the section existed) → appends it with the
 *    usual blank-line separator.
 * Never returns null — a missing section is added, not a reason to skip.
 * Only ever call this for NON-orchestrator agents (the orchestrator delegates
 * and must not carry leaf-worker discipline).
 */
export function resyncAgentDisciplineSection(content: string): string {
  const heading = "## Working discipline\n";
  const canonical = heading + WORKING_DISCIPLINE_BODY + "\n";
  const headingIdx = content.indexOf(heading);
  if (headingIdx === -1) {
    const base = content.endsWith("\n") ? content : content + "\n";
    return base + "\n" + canonical;
  }
  const updated = content.slice(0, headingIdx) + canonical;
  return updated === content ? content : updated;
}

