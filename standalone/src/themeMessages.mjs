// TycoonAgents standalone — non-AI theme message handlers (project-plan task
// pB-t1: "Standalone theme host: wire the 4 non-AI theme messages").
//
// WHY THIS FILE EXISTS SEPARATE FROM src/extension/themeService.ts: that
// module (and its siblings themeStorage.ts / themeImageReviewState.ts) do
// `import * as vscode from 'vscode'` at module load time, so `require()`ing
// the COMPILED out/src/extension/themeService.js from this vscode-less
// process throws immediately (`Cannot find module 'vscode'`) — see
// themeFileStoreFs.mjs's module header for the same constraint on the file
// storage layer. This module REIMPLEMENTS the four read-mostly, non-AI theme
// operations (list / select / delete / review) directly against the
// vscode-free `ThemeFileStore` interface (src/extension/themeFileStore.ts)
// and its relative-path builders (re-exported from themeFileStoreFs.mjs),
// mirroring themeService.ts's LOGIC and RESPONSE SHAPES closely enough that
// media/main.js (unmodified) renders identically, without ever importing
// themeService.ts itself.
//
// The ONE piece of genuinely vscode-free, pure logic this module reuses
// rather than re-implements is `summarizeThemeApproval` from
// src/extension/themeApproval.ts (no imports at all in that file) — lazily
// required from the compiled out/src/extension/themeApproval.js via
// createRequire, the exact same "single source of truth from out/" pattern
// themeFileStoreFs.mjs already established for the path builders. Everything
// else here (list/select/delete/review assembly) is a deliberate,
// standalone-only reimplementation.
//
// SIMPLIFICATIONS vs. the real extension (documented, not silently dropped):
//   - SELECT_THEME does not run upgradeThemeManifest (themeMigration.ts) —
//     a theme generated by a current release needs no migration; a very old
//     legacy manifest may render with stale/missing fields in the standalone
//     until a later task adds this.
//   - GET_THEME_IMAGE_REVIEW does not synthesize "expected" placeholder
//     cards for boards that were never generated (createReviewItems, which
//     needs the full ThemePlan + translator pipeline), does not recover
//     legacy/inferred review items, and always reports `has_raw_atlas:
//     false` (no re-slice-from-raw support yet) and no `currentPrompt`
//     (media/main.js does not read that field, so it is safely omitted).
//     It only reflects whatever review.json already has saved. Good enough
//     for viewing/approving/rejecting already-generated boards; generation
//     itself is a separate, later (AI-touching) task.
//   - No per-theme badge/rebirth/build-progress persistence yet (pA/pB
//     scope) — SELECT_THEME always reports the safe defaults
//     `unlocked_badge_ids: []`, `rebirth_state: null`, `savedBuildProgress: 0`
//     (0 is the REAL wire type — see media/main.js's
//     `typeof payload.savedBuildProgress === "number" ? ... : 0` check).
//   - DELETE_THEME never shows a confirmation dialog server-side (unlike the
//     VS Code extension's native modal) — the standalone runs in a real
//     browser, so the CLIENT is expected to gate this with its own
//     `window.confirm()` before ever sending the message; the server just
//     deletes on receipt, exactly like every other message handler here.
//
// Node built-ins only. No vscode import, direct or transitive.

import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import {
  themesDirectoryPath,
  themeDirectoryPath,
  themeManifestPath,
  themeFramesPath,
  themeReviewPath,
  themeImagesDirectoryPath,
} from './themeFileStoreFs.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '..', '..');
const THEME_APPROVAL_JS = path.join(REPO_ROOT, 'out', 'src', 'extension', 'themeApproval.js');

const require = createRequire(import.meta.url);

let _themeApprovalModule;
function summarizeThemeApproval(items) {
  if (!_themeApprovalModule) {
    _themeApprovalModule = require(THEME_APPROVAL_JS);
  }
  return _themeApprovalModule.summarizeThemeApproval(items);
}

// ── Wire-string contract (duplicated from src/host/vscode/messages.ts's MSG
// object — see standalone/test/themeMessageContract.test.mjs, which parses
// messages.ts's SOURCE and asserts every value below still matches it. Same
// deliberate-duplication posture as stateFeed.mjs's MSG_STATE: messages.ts
// imports zod + ./projectPlan, outside the standalone's verified vscode-free
// bridge surface, so it cannot be imported directly. ─────────────────────
export const MSG_WIRE = {
  LIST_THEMES: 'LIST_THEMES',
  THEMES_LIST: 'THEMES_LIST',
  SELECT_THEME: 'SELECT_THEME',
  THEME_INITIALIZED: 'THEME_INITIALIZED',
  THEME_NONE: 'THEME_NONE',
  DELETE_THEME: 'DELETE_THEME',
  GET_THEME_IMAGE_REVIEW: 'GET_THEME_IMAGE_REVIEW',
  THEME_IMAGE_REVIEW: 'THEME_IMAGE_REVIEW',
  THEME_GENERATION_ERROR: 'THEME_GENERATION_ERROR',
};

/** Mirrors src/extension/themeService.ts's isThemeId exactly. */
export function isThemeId(value) {
  return typeof value === 'string' && /^[a-z0-9_]+$/.test(value);
}

async function readJsonSafe(store, relativePath) {
  try {
    const bytes = await store.readFile(relativePath);
    return JSON.parse(Buffer.from(bytes).toString('utf8'));
  } catch {
    return undefined;
  }
}

/** Mirrors themeService.ts's diskUsage: recursive file-size sum, 0 on any error. */
async function diskUsageBytes(store, relativePath) {
  let stat;
  try {
    stat = await store.stat(relativePath);
  } catch {
    return 0;
  }
  if (stat.isFile) return stat.size;
  if (!stat.isDirectory) return 0;
  let entries;
  try {
    entries = await store.readdir(relativePath);
  } catch {
    return 0;
  }
  const sizes = await Promise.all(entries.map((entry) => diskUsageBytes(store, `${relativePath}/${entry.name}`)));
  return sizes.reduce((total, size) => total + size, 0);
}

/**
 * Mirrors themeService.ts's listThemes() for the modern per-directory
 * layout only (no legacy flat-file fallback — the standalone never writes
 * that layout). Returns theme_id/display_name/size_bytes plus the
 * ThemeApprovalSummary fields (total/accepted/export_ready) the themes-modal
 * card in media/main.js reads.
 */
export async function listThemesFromStore(store) {
  const results = new Map();
  try {
    const entries = await store.readdir(themesDirectoryPath());
    for (const entry of entries) {
      if (!entry.isDirectory || !isThemeId(entry.name)) continue;
      const manifest = await readJsonSafe(store, themeManifestPath(entry.name));
      if (manifest) {
        results.set(entry.name, { theme_id: entry.name, display_name: manifest.display_name ?? entry.name });
      }
    }
  } catch {
    // The themes/ directory is created on first generation.
  }

  const sorted = [...results.values()].sort((a, b) => a.display_name.localeCompare(b.display_name));
  return Promise.all(
    sorted.map(async (theme) => {
      const [reviewDoc, sizeBytes] = await Promise.all([
        readJsonSafe(store, themeReviewPath(theme.theme_id)),
        diskUsageBytes(store, themeDirectoryPath(theme.theme_id)),
      ]);
      const approval = summarizeThemeApproval(reviewDoc?.items);
      return { ...theme, ...approval, size_bytes: sizeBytes };
    }),
  );
}

/** Mirrors themeService.ts's loadTheme() for the modern layout only. */
export async function loadThemeFromStore(store, themeId) {
  if (!isThemeId(themeId)) return undefined;
  const manifest = await readJsonSafe(store, themeManifestPath(themeId));
  const frames = await readJsonSafe(store, themeFramesPath(themeId));
  if (!manifest || !frames) return undefined;
  return { manifest, frames };
}

// ── Message handlers ────────────────────────────────────────────────────
// Each takes the fs-backed ThemeFileStore + the server's broadcast(eventName,
// data) (see server.mjs) and posts the SSE "message" event media/main.js's
// window 'message' listener expects — identical wire shape to
// webview.postMessage() in src/host/vscode/panel.ts.

export async function handleListThemes(store, broadcast) {
  const themes = await listThemesFromStore(store);
  broadcast('message', { type: MSG_WIRE.THEMES_LIST, payload: { themes } });
}

/** Mirrors panel.ts's _activateTheme(): THEME_INITIALIZED on success,
 * THEME_GENERATION_ERROR with the same "Theme not found." message on a
 * missing/incomplete theme. */
export async function handleSelectTheme(store, broadcast, themeId) {
  const loaded = await loadThemeFromStore(store, themeId);
  if (!loaded) {
    broadcast('message', {
      type: MSG_WIRE.THEME_GENERATION_ERROR,
      payload: { message: 'Theme not found.' },
    });
    return;
  }
  broadcast('message', {
    type: MSG_WIRE.THEME_INITIALIZED,
    payload: {
      manifest: loaded.manifest,
      frames: loaded.frames,
      is_editor_mode: false,
      // No per-theme badge/rebirth/build-progress persistence in the
      // standalone yet (see module header) — safe defaults only.
      unlocked_badge_ids: [],
      rebirth_state: null,
      savedBuildProgress: 0,
    },
  });
}

/** Mirrors panel.ts's DELETE_THEME handler MINUS the native confirmation
 * modal — see module header: the browser client is responsible for gating
 * this with its own confirm() before ever sending DELETE_THEME. */
export async function handleDeleteTheme(store, broadcast, themeId) {
  let deletedThemeId;
  let deleteError;
  try {
    if (!isThemeId(themeId)) throw new Error('Invalid theme ID.');
    const existing = await listThemesFromStore(store);
    if (!existing.some((candidate) => candidate.theme_id === themeId)) {
      throw new Error('Theme not found.');
    }
    try {
      await store.remove(themeDirectoryPath(themeId), { recursive: true });
    } catch (err) {
      if (err?.code !== 'FileNotFound') throw err;
    }
    deletedThemeId = themeId;
  } catch (err) {
    deleteError = String(err?.message ?? err);
  }
  const themes = await listThemesFromStore(store);
  broadcast('message', {
    type: MSG_WIRE.THEMES_LIST,
    payload: { themes, deleted_theme_id: deletedThemeId, delete_error: deleteError },
  });
}

/**
 * Mirrors panel.ts's _postThemeImageReview() closely enough for the review
 * modal to render already-generated/already-reviewed boards — see the
 * SIMPLIFICATIONS note in this module's header for what is intentionally
 * left out (expected-placeholder synthesis, has_raw_atlas, currentPrompt,
 * legacy inference).
 *
 * @param {string} imageBaseUrl URL prefix the image route is mounted at
 *   (server.mjs serves `${imageBaseUrl}/<theme_id>/<filename>`). Defaults to
 *   '/theme-images', matching server.mjs's actual route.
 */
export async function handleGetThemeImageReview(store, broadcast, themeId, { imageBaseUrl = '/theme-images' } = {}) {
  if (!isThemeId(themeId)) return;
  try {
    const [manifest, frames, reviewDoc] = await Promise.all([
      readJsonSafe(store, themeManifestPath(themeId)),
      readJsonSafe(store, themeFramesPath(themeId)),
      readJsonSafe(store, themeReviewPath(themeId)),
    ]);
    const framesMap = frames ?? {};
    const items = Array.isArray(reviewDoc?.items) ? reviewDoc.items : [];

    let existingFilenames = new Set();
    try {
      const entries = await store.readdir(themeImagesDirectoryPath(themeId));
      existingFilenames = new Set(entries.filter((entry) => entry.isFile).map((entry) => entry.name));
    } catch {
      // images/ directory not created yet — no generated art at all.
    }

    const outItems = items.map((item) => {
      const hasImage = Boolean(item.filename) && existingFilenames.has(item.filename);
      // Mirrors themeGenerationState.ts's isThemeGenerationItemComplete.
      const frameKeys = Array.isArray(item.frame_keys) ? item.frame_keys : [];
      const generated =
        hasImage
        && (frameKeys.length === 0
          || frameKeys.every((key) => Array.isArray(framesMap[key]) && framesMap[key].length > 0));
      return {
        ...item,
        generated,
        has_raw_atlas: false,
        image_src: hasImage
          ? `${imageBaseUrl}/${themeId}/${encodeURIComponent(item.filename)}?revision=${item.revision ?? 0}`
          : '',
      };
    });

    broadcast('message', {
      type: MSG_WIRE.THEME_IMAGE_REVIEW,
      payload: {
        theme_id: themeId,
        display_name: reviewDoc?.display_name ?? manifest?.display_name ?? themeId,
        generation_active: false,
        pause_for_review: true,
        waiting_for_review_item_id: undefined,
        items: outItems,
      },
    });
  } catch (err) {
    broadcast('message', {
      type: MSG_WIRE.THEME_IMAGE_REVIEW,
      payload: { theme_id: themeId, items: [], error: String(err) },
    });
  }
}
