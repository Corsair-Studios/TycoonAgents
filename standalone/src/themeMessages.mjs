/**
 * Board-aligned recovery: mirrors themeService.ts's
 * recoverBoardAlignedReviewImages + the writeFile/initializeThemeImageReviewDocument
 * calls in ensureThemeReviewImages. Runs only when `manifest` exists and no
 * review.json is present yet. Writes composed board PNGs under
 * themeImagesDirectoryPath(themeId) and a review.json (version 1, all items
 * `pending`, `updated_at` epoch — matching initializeThemeImageReviewDocument's
 * shape closely enough for this module's own readback) through `store`.
 * Returns the written items array (without `updated_at`... actually WITH it,
 * see below) so the caller can use it immediately without a re-read.
 * Never throws: any failure is swallowed and undefined is returned, exactly
 * like ensureThemeReviewImages's own try/catch around this same recovery.
 */
async function recoverThemeReviewBoards(store, themeId, manifest, framesMap) {
  try {
    const { createReviewItems } = themeServiceModule();
    const { composeRecoveredBoardImages } = themeBoardRecoveryModule();
    const { normalizeThemePlan, themePlanCreativeDirection } = themePlanModule();
    const { themePlanPath, legacyPlanPath, themeImagesDirectoryPath: imagesDirPath } = themeFileStoreModule();

    const savedPlan = (await readJsonSafe(store, themePlanPath(themeId)))
      ?? (await readJsonSafe(store, legacyPlanPath(themeId)));
    const plan = normalizeThemePlan(savedPlan ?? {}, manifest.display_name);
    const creativeDirection = themePlanCreativeDirection(plan);
    const items = createReviewItems(plan, manifest, creativeDirection);
    const files = await composeRecoveredBoardImages(items, framesMap);

    const directoryPath = imagesDirPath(themeId);
    await store.mkdirp(directoryPath);
    for (const file of files) {
      await store.writeFile(`${directoryPath}/${file.filename}`, file.data);
    }

    const updatedAt = new Date(0).toISOString();
    const reviewItems = items.map((item) => ({ ...item, updated_at: updatedAt }));
    await store.writeFile(
      themeReviewPath(themeId),
      new TextEncoder().encode(JSON.stringify({
        version: 1,
        theme_id: themeId,
        display_name: manifest.display_name,
        items: reviewItems,
      })),
    );
    return reviewItems;
  } catch (err) {
    console.warn(`[tycoonagents-standalone] themeMessages: could not recover review boards for ${themeId}:`, err);
    return undefined;
  }
}

