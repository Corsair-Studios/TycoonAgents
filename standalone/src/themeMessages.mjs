// TycoonAgents standalone — non-AI theme message handlers (project-plan task
// pB-t1: "Standalone theme host: wire the 4 non-AI theme messages").
//
// WHY THIS FILE EXISTS SEPARATE FROM src/extension/themeService.ts: that
// module (and its siblings themeStorage.ts / themeImageReviewState.ts) do
// `import * as vscode from 'vscode'` at module load time, so `require()`ing
// the COMPILED out/src/extension/themeService.js from this vscode-less
// process throws immediately (`Cannot find module 'vscode'`) — see
// themeFileStoreFs.mjs's module header for the same constraint on the file
// storage layer. This module REIMPLEMENTS the four read-mostly, non-AI theme
// operations (list / select / delete / review) directly against the
// vscode-free `ThemeFileStore` interface (src/extension/themeFileStore.ts)
// and its relative-path builders (re-exported from themeFileStoreFs.mjs),
// mirroring themeService.ts's LOGIC and RESPONSE SHAPES closely enough that
// media/main.js (unmodified) renders identically, without ever importing
// themeService.ts itself.
//
// The ONE piece of genuinely vscode-free, pure logic this module reuses
// rather than re-implements is `summarizeThemeApproval` from
// src/extension/themeApproval.ts (no imports at all in that file) — lazily
// required from the compiled out/src/extension/themeApproval.js via
// createRequire, the exact same "single source of truth from out/" pattern
// themeFileStoreFs.mjs already established for the path builders. Everything
// else here (list/select/delete/review assembly) is a deliberate,
// standalone-only reimplementation.
//
// SIMPLIFICATIONS vs. the real extension (documented, not silently dropped):
//   - SELECT_THEME does not run upgradeThemeManifest (themeMigration.ts) —
//     a theme generated by a current release needs no migration; a very old
//     legacy manifest may render with stale/missing fields in the standalone
//     until a later task adds this.
//   - GET_THEME_IMAGE_REVIEW (project-plan task p9-t4) DOES now recover a
//     missing review.json the same way themeService.ts's
//     ensureThemeReviewImages does on the VS Code host: board-aligned
//     recovery only (recoverThemeReviewBoards, below, ports the
//     createReviewItems + composeRecoveredBoardImages orchestration
//     directly since ensureThemeReviewImages itself cannot be called from
//     this vscode-less process — see that function's own comment). It does
//     NOT synthesize "expected" placeholder cards for a theme that already
//     HAS a review.json (a saved-but-incomplete board contract), does not
//     run the legacy per-key/inferred-item fallback recovery path, and
//     always reports `has_raw_atlas: false` (no re-slice-from-raw support
//     yet) and no `currentPrompt` (media/main.js does not read that field,
//     so it is safely omitted). Good enough for viewing/approving/rejecting
//     already-generated boards; generation itself is a separate, later
//     (AI-touching) task.
//   - No per-theme badge/rebirth/build-progress persistence yet (pA/pB
//     scope) — SELECT_THEME always reports the safe defaults
//     `unlocked_badge_ids: []`, `rebirth_state: null`, `savedBuildProgress: 0`
//     (0 is the REAL wire type — see media/main.js's
//     `typeof payload.savedBuildProgress === "number" ? ... : 0` check).
//   - DELETE_THEME never shows a confirmation dialog server-side (unlike the
//     VS Code extension's native modal) — the standalone runs in a real
//     browser, so the CLIENT is expected to gate this with its own
//     `window.confirm()` before ever sending the message; the server just
//     deletes on receipt, exactly like every other message handler here.
//
// Node built-ins only. No vscode import, direct or transitive.

