/** Mirrors src/extension/themeService.ts's isThemeId exactly. */
export function isThemeId(value) {
  return typeof value === 'string' && /^[a-z0-9_]+$/.test(value);
}

async function readJsonSafe(store, relativePath) {
  try {
    const bytes = await store.readFile(relativePath);
    return JSON.parse(Buffer.from(bytes).toString('utf8'));
  } catch {
    return undefined;
  }
}

/** Mirrors themeService.ts's diskUsage: recursive file-size sum, 0 on any error. */
async function diskUsageBytes(store, relativePath) {
  let stat;
  try {
    stat = await store.stat(relativePath);
  } catch {
    return 0;
  }
  if (stat.isFile) return stat.size;
  if (!stat.isDirectory) return 0;
  let entries;
  try {
    entries = await store.readdir(relativePath);
  } catch {
    return 0;
  }
  const sizes = await Promise.all(entries.map((entry) => diskUsageBytes(store, `${relativePath}/${entry.name}`)));
  return sizes.reduce((total, size) => total + size, 0);
}

/**
 * Mirrors themeService.ts's themeBoardCountsFromFrames (p77-t2): counts
 * frames.json keys — every generated OR uploaded board writes its slot into
 * frames.json, so this cheap key count answers "does this theme have
 * anything to review" without a directory scan.
 */
export function themeBoardCounts(frames) {
  const boardCount = frames ? Object.keys(frames).length : 0;
  return { hasBoards: boardCount > 0, boardCount };
}

/** Same as `themeBoardCounts`, reading frames.json for `themeId` from `store`. */
export async function themeBoardCountsFromStore(store, themeId) {
  if (!isThemeId(themeId)) return { hasBoards: false, boardCount: 0 };
  const frames = await readJsonSafe(store, themeFramesPath(themeId));
  return themeBoardCounts(frames);
}

/**
 * Mirrors themeService.ts's listThemes() for the modern per-directory
 * layout only (no legacy flat-file fallback — the standalone never writes
 * that layout). Returns theme_id/display_name/size_bytes plus the
 * ThemeApprovalSummary fields (total/accepted/export_ready) the themes-modal
 * card in media/main.js reads.
 */
export async function listThemesFromStore(store) {
  const results = new Map();
  try {
    const entries = await store.readdir(themesDirectoryPath());
    for (const entry of entries) {
      if (!entry.isDirectory || !isThemeId(entry.name)) continue;
      const manifest = await readJsonSafe(store, themeManifestPath(entry.name));
      if (manifest) {
        results.set(entry.name, { theme_id: entry.name, display_name: manifest.display_name ?? entry.name });
      }
    }
  } catch {
    // The themes/ directory is created on first generation.
  }

  const sorted = [...results.values()].sort((a, b) => a.display_name.localeCompare(b.display_name));
  return Promise.all(
    sorted.map(async (theme) => {
      const [reviewDoc, sizeBytes, boardCounts] = await Promise.all([
        readJsonSafe(store, themeReviewPath(theme.theme_id)),
        diskUsageBytes(store, themeDirectoryPath(theme.theme_id)),
        themeBoardCountsFromStore(store, theme.theme_id),
      ]);
      const approval = summarizeThemeApproval(reviewDoc?.items);
      return { ...theme, ...approval, size_bytes: sizeBytes, ...boardCounts };
    }),
  );
}

/** Mirrors themeService.ts's loadTheme() for the modern layout only. */
export async function loadThemeFromStore(store, themeId) {
  if (!isThemeId(themeId)) return undefined;
  const manifest = await readJsonSafe(store, themeManifestPath(themeId));
  const frames = await readJsonSafe(store, themeFramesPath(themeId));
  if (!manifest || !frames) return undefined;
  return { manifest, frames };
}

// ── Message handlers ────────────────────────────────────────────────────
// Each takes the fs-backed ThemeFileStore + the server's broadcast(eventName,
// data) (see server.mjs) and posts the SSE "message" event media/main.js's
// window 'message' listener expects — identical wire shape to
// webview.postMessage() in src/host/vscode/panel.ts.

export async function handleListThemes(store, broadcast) {
  const themes = await listThemesFromStore(store);
  broadcast('message', { type: MSG_WIRE.THEMES_LIST, payload: { themes } });
}

/** Mirrors panel.ts's _activateTheme(): THEME_INITIALIZED on success,
 * THEME_GENERATION_ERROR with the same "Theme not found." message on a
 * missing/incomplete theme. */
/**
 * @param {object} [progress] optional `{ appData, projectRoot }` — when
 * `appData` (an appData.mjs handle) is supplied, `unlocked_badge_ids` and
 * `rebirth_state` are read from the real persisted stores (see
 * getUnlockedBadgesStandalone/getRebirthStateStandalone above), scoped to
 * `projectRoot`. Omitted (or `appData` absent) falls back to the prior
 * `[]`/`null` safe defaults — `savedBuildProgress` has no persistence wired
 * up yet either way (still out of scope; unrelated to badges/rebirth).
 */
export async function handleSelectTheme(store, broadcast, themeId, progress = {}) {
  const loaded = await loadThemeFromStore(store, themeId);
  if (!loaded) {
    broadcast('message', {
      type: MSG_WIRE.THEME_GENERATION_ERROR,
      payload: { message: 'Theme not found.' },
    });
    return;
  }
  const { appData, projectRoot } = progress || {};
  broadcast('message', {
    type: MSG_WIRE.THEME_INITIALIZED,
    payload: {
      manifest: loaded.manifest,
      frames: loaded.frames,
      is_editor_mode: false,
      unlocked_badge_ids: getUnlockedBadgesStandalone(appData, projectRoot, themeId),
      rebirth_state: getRebirthStateStandalone(appData, projectRoot, themeId),
      // No per-theme build-progress persistence in the standalone yet (see
      // module header) — safe default only.
      savedBuildProgress: 0,
      ...themeBoardCounts(loaded.frames),
    },
  });
}

/** Mirrors panel.ts's DELETE_THEME handler MINUS the native confirmation
 * modal — see module header: the browser client is responsible for gating
 * this with its own confirm() before ever sending DELETE_THEME. */
export async function handleDeleteTheme(store, broadcast, themeId) {
  let deletedThemeId;
  let deleteError;
  try {
    if (!isThemeId(themeId)) throw new Error('Invalid theme ID.');
    const existing = await listThemesFromStore(store);
    if (!existing.some((candidate) => candidate.theme_id === themeId)) {
      throw new Error('Theme not found.');
    }
    try {
      await store.remove(themeDirectoryPath(themeId), { recursive: true });
    } catch (err) {
      if (err?.code !== 'FileNotFound') throw err;
    }
    deletedThemeId = themeId;
  } catch (err) {
    deleteError = String(err?.message ?? err);
  }
  const themes = await listThemesFromStore(store);
  broadcast('message', {
    type: MSG_WIRE.THEMES_LIST,
    payload: { themes, deleted_theme_id: deletedThemeId, delete_error: deleteError },
  });
}

/**
 * Mirrors panel.ts's _postThemeImageReview() closely enough for the review
 * modal to render already-generated/already-reviewed boards — see the
 * SIMPLIFICATIONS note in this module's header for what is intentionally
 * left out (expected-placeholder synthesis, has_raw_atlas, currentPrompt,
 * legacy inference).
 *
 * @param {string} imageBaseUrl URL prefix the image route is mounted at
 *   (server.mjs serves `${imageBaseUrl}/<theme_id>/<filename>`). Defaults to
 *   '/theme-images', matching server.mjs's actual route.
 */
export async function handleGetThemeImageReview(store, broadcast, themeId, { imageBaseUrl = '/theme-images' } = {}) {
  if (!isThemeId(themeId)) return;
  try {
    const [manifest, frames, reviewDoc] = await Promise.all([
      readJsonSafe(store, themeManifestPath(themeId)),
      readJsonSafe(store, themeFramesPath(themeId)),
      readJsonSafe(store, themeReviewPath(themeId)),
    ]);
    const framesMap = frames ?? {};
    let effectiveReviewDoc = reviewDoc;
    // No review.json yet: recover it (board-aligned, magenta placeholder
    // boards composed from frames.json) the same way ensureThemeReviewImages
    // does on the VS Code host, so the two hosts converge on identical
    // on-disk state (review.json + images/). Only attempted when a manifest
    // exists — a manifest-less theme id can't synthesize a board contract.
    if (!effectiveReviewDoc && manifest) {
      const recoveredItems = await recoverThemeReviewBoards(store, themeId, manifest, framesMap);
      if (recoveredItems) {
        effectiveReviewDoc = { display_name: manifest.display_name, items: recoveredItems };
      }
    }
    const items = Array.isArray(effectiveReviewDoc?.items) ? effectiveReviewDoc.items : [];

    // Prefill the same stale-descriptions signal panel.ts sends (see
    // themeDescriptionsStale in themePlan.ts) so both hosts' webviews can
    // show the re-derive affordance identically.
    let currentPlan;
    if (manifest) {
      const { normalizeThemePlan, themePlanPath, legacyPlanPath } = (() => {
        const mod = themePlanModule();
        const fileStore = themeFileStoreModule();
        return { normalizeThemePlan: mod.normalizeThemePlan, themePlanPath: fileStore.themePlanPath, legacyPlanPath: fileStore.legacyPlanPath };
      })();
      const savedPlan = (await readJsonSafe(store, themePlanPath(themeId)))
        ?? (await readJsonSafe(store, legacyPlanPath(themeId)));
      if (savedPlan) currentPlan = normalizeThemePlan(savedPlan, manifest.display_name);
    }

    let existingFilenames = new Set();
    try {
      const entries = await store.readdir(themeImagesDirectoryPath(themeId));
      existingFilenames = new Set(entries.filter((entry) => entry.isFile).map((entry) => entry.name));
    } catch {
      // images/ directory not created yet — no generated art at all.
    }

    const outItems = items.map((item) => {
      const hasImage = Boolean(item.filename) && existingFilenames.has(item.filename);
      // Mirrors themeGenerationState.ts's isThemeGenerationItemComplete.
      const frameKeys = Array.isArray(item.frame_keys) ? item.frame_keys : [];
      const generated =
        hasImage
        && (frameKeys.length === 0
          || frameKeys.every((key) => Array.isArray(framesMap[key]) && framesMap[key].length > 0));
      // Mirrors panel.ts's _postThemeImageReview frame_slots computation
      // (src/host/vscode/panel.ts:3088-3101): one entry per frame_keys[i]
      // using that key's first stored frame, EXCEPT the single-key/
      // multi-stored-frame shape (character boards: one frame_keys entry
      // whose stored array holds all 16 poses), which instead enumerates
      // WITHIN that key's stored frames, one entry per pose with an `index`.
      const frameSlots = (() => {
        if (frameKeys.length === 1) {
          const soleKeyFrames = framesMap[frameKeys[0]] ?? [];
          if (soleKeyFrames.length > 1) {
            return soleKeyFrames.map((data, index) => ({ key: frameKeys[0], index, data: data ?? '' }));
          }
        }
        return frameKeys.map((key) => ({ key, data: framesMap[key]?.[0] ?? '' }));
      })();
      return {
        ...item,
        generated,
        has_raw_atlas: false,
        frame_slots: frameSlots,
        image_src: hasImage
          ? `${imageBaseUrl}/${themeId}/${encodeURIComponent(item.filename)}?revision=${item.revision ?? 0}`
          : '',
      };
    });

    broadcast('message', {
      type: MSG_WIRE.THEME_IMAGE_REVIEW,
      payload: {
        theme_id: themeId,
        display_name: effectiveReviewDoc?.display_name ?? manifest?.display_name ?? themeId,
        generation_active: false,
        pause_for_review: true,
        waiting_for_review_item_id: undefined,
        creative_direction: currentPlan?.creative_direction,
        descriptionsStale: currentPlan ? themePlanModule().themeDescriptionsStale(currentPlan) : false,
        descriptionsDirection: currentPlan?.descriptions_direction,
        items: outItems,
        ...themeBoardCounts(framesMap),
      },
    });
  } catch (err) {
    broadcast('message', {
      type: MSG_WIRE.THEME_IMAGE_REVIEW,
      payload: { theme_id: themeId, items: [], error: String(err), hasBoards: false, boardCount: 0 },
    });
  }
}
