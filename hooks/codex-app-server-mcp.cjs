// --- MCP-facing framing (this shim's own stdio toward the caller) ---------

function writeMessage(obj) {
  process.stdout.write(JSON.stringify(obj) + "\n");
}
function respond(id, result) {
  writeMessage({ jsonrpc: "2.0", id, result });
}
function respondError(id, code, message) {
  writeMessage({ jsonrpc: "2.0", id, error: { code, message } });
}
const PROVIDER = "codex-app-server";

function isErrorResult(text, kind, model) {
  return providerErrorResult({ provider: PROVIDER, model, text, kind });
}

/**
 * Manages exactly one spawned `codex app-server` child process for the
 * shim's lifetime: sends requests (assigns its own JSON-RPC ids, resolves on
 * the matching id-keyed response), routes notifications to registered
 * per-(threadId,turnId) turn listeners — so two overlapping turns on the
 * same thread (e.g. concurrent codex-reply calls) never collide — and
 * auto-declines any id-bearing approval-request method the child sends
 * (never hangs a turn).
 */
class AppServerClient {
  constructor(binaryPath, extraArgs) {
    this.binaryPath = binaryPath;
    this.extraArgs = extraArgs || [];
    this.child = null;
    this.nextId = 1;
    this.pending = new Map(); // id -> {resolve, reject}
    // Keyed by `${threadId}:${turnId}`, NOT threadId alone — two overlapping
    // turns on the same thread (e.g. concurrent codex-reply calls) get
    // distinct turnIds from their own turn/start responses, so this must
    // disambiguate by turn or the second call's registration overwrites the
    // first's listener and the first hangs until timeout.
    this.turnListeners = new Map(); // key -> {turnId, threadId, text, resolve, reject, timer}
    // Notifications (item/*/turn/completed) can arrive on the same
    // synchronous readline flush as the turn/start response that hands us
    // the turnId, i.e. before our await-continuation runs to register the
    // listener. Early arrivals are buffered here by the same key and
    // consumed/merged when the listener is registered.
    this.pendingTurnState = new Map(); // key -> {text, completed, turn}
    this.initialized = null;
    // `${threadId}:${turnId}` -> grace timer for a timed-out turn we asked the child to interrupt.
    this.interrupting = new Map();
  }

  ensureSpawned() {
    if (this.child) return;
    const args = ["app-server", "--stdio", ...this.extraArgs];
    // Reuses codex-mcp-launcher.cjs's own needsShell() (a bare command name,
    // or a Windows .cmd/.bat shim such as an npm-global install or a test
    // fixture wrapper, is not a native executable CreateProcess can launch
    // directly with shell:false) instead of re-implementing a narrower
    // .cmd/.bat-only check here — discoverCodexBinary can return a bare
    // "codex" (PATH-resolved) or an unresolved shim path, both of which
    // previously fell through this file's own check and spawned with
    // shell:false, throwing ENOENT (p69-t2,
    // docs/codex-reviewer-onboarding-friction-2026-09-18.md #6).
    const shell = needsShell(this.binaryPath);
    const child = spawn(this.binaryPath, args, {
      shell,
      windowsHide: true,
      stdio: ["pipe", "pipe", "pipe"],
    });
    this.child = child;
    this.child.on("error", (err) => {
      const message = `[codex-app-server-mcp] failed to spawn app-server child "${this.binaryPath}": ${err && err.message}`;
      process.stderr.write(`${message}\n`);
      // Reject every pending request/turn immediately instead of leaving
      // them to hang until the (default 600s) timeout — a spawn failure
      // (e.g. ENOENT) is permanent for this child, so waiting for it to
      // "complete" is never useful (p69-t2, friction-doc #6).
      const spawnErr = new Error(message);
      for (const { reject } of this.pending.values()) reject(spawnErr);
      this.pending.clear();
      for (const listener of this.turnListeners.values()) {
        clearTimeout(listener.timer);
        listener.reject(spawnErr);
      }
      this.turnListeners.clear();
      this.pendingTurnState.clear();
      if (this.child === child) this.child = null;
    });
    this.child.on("exit", (code, signal) => {
      process.stderr.write(`[codex-app-server-mcp] app-server child exited (code=${code}, signal=${signal})\n`);
      const err = new Error(`app-server child exited unexpectedly (code=${code}, signal=${signal})`);
      for (const { reject } of this.pending.values()) reject(err);
      this.pending.clear();
      for (const listener of this.turnListeners.values()) {
        clearTimeout(listener.timer);
        listener.reject(err);
      }
      this.turnListeners.clear();
      this.pendingTurnState.clear();
      this.clearInterrupts();
      if (this.child === child) this.child = null;
    });
    this.child.stderr.on("data", (chunk) => {
      process.stderr.write(`[codex-app-server-mcp:child] ${chunk}`);
    });

    const rl = readline.createInterface({ input: this.child.stdout, terminal: false });
    rl.on("line", (line) => this.handleChildLine(line));
  }

  handleChildLine(line) {
    const trimmed = line.trim();
    if (!trimmed) return;
    let msg;
    try {
      msg = JSON.parse(trimmed);
    } catch {
      process.stderr.write(`[codex-app-server-mcp] ignoring malformed line from app-server child: ${trimmed}\n`);
      return;
    }

    // Id-bearing message FROM the child with a `method` is a REQUEST the
    // child expects us to answer (approval requests). Id-bearing message
    // with no `method` is a RESPONSE to one of our own requests.
    if (msg.method && msg.id !== undefined && msg.id !== null) {
      this.handleChildRequest(msg);
      return;
    }
    if (msg.id !== undefined && msg.id !== null && !msg.method) {
      const waiter = this.pending.get(msg.id);
      if (waiter) {
        this.pending.delete(msg.id);
        if (msg.error) waiter.reject(new Error(msg.error.message || JSON.stringify(msg.error)));
        else waiter.resolve(msg.result);
      }
      return;
    }
    if (msg.method) {
      this.handleChildNotification(msg);
    }
  }

  /**
   * Any id-bearing request from the child is treated as an approval request
   * and declined — this shim never blocks a turn on human/agent approval.
   * Decision shape: the only fixture evidence available (see
   * test/fixtures/codex-hooks/app-server/session-with-subagents.redacted.json)
   * is `availableDecisions` listing a bare string `"cancel"` alongside
   * `"accept"` and an `acceptWithExecpolicyAmendment` object — no captured
   * transcript shows the actual RESPONSE frame the app-server accepts for a
   * decline, so replying `result:"cancel"` is a best-effort guess against
   * that enum, unverified against a live approval round-trip. Configurable
   * via CODEX_APP_SERVER_DECLINE_DECISION in case that guess is wrong for a
   * given build.
   */
  handleChildRequest(msg) {
    const decision = process.env.CODEX_APP_SERVER_DECLINE_DECISION || "cancel";
    process.stderr.write(
      `[codex-app-server-mcp] auto-declining child request "${msg.method}" (id=${msg.id}) with decision "${decision}" — approvals are never granted by this shim.\n`,
    );
    this.send({ jsonrpc: "2.0", id: msg.id, result: decision });
  }

  static key(threadId, turnId) {
    return `${threadId}:${turnId}`;
  }

  /** Merges `patch` into the buffered pre-registration state for `key`, creating it if absent. */
  bufferPendingState(key, patch) {
    const state = this.pendingTurnState.get(key) || { text: "", completed: false, turn: null };
    Object.assign(state, patch);
    this.pendingTurnState.set(key, state);
  }

  handleChildNotification(msg) {
    const { method, params } = msg;
    if (!params) return;
    const threadId = params.threadId;
    const turnId = params.turnId || (params.turn && params.turn.id);
    if (!threadId || !turnId) return; // can't route without both — not a turn-scoped notification we track

    const key = AppServerClient.key(threadId, turnId);

    if (method === "item/agentMessage/delta" && typeof params.delta === "string") {
      const listener = this.turnListeners.get(key);
      if (listener) listener.text += params.delta;
      else this.bufferPendingState(key, { text: (this.pendingTurnState.get(key) || { text: "" }).text + params.delta });
      return;
    }

    if (method === "item/completed" && params.item && params.item.type === "agentMessage" && typeof params.item.text === "string") {
      const listener = this.turnListeners.get(key);
      if (listener) listener.text = params.item.text;
      else this.bufferPendingState(key, { text: params.item.text });
      return;
    }

    if (method === "turn/completed") {
      const grace = this.interrupting.get(key);
      if (grace) {
        // The interrupted turn wound down: no need to kill the child.
        clearTimeout(grace);
        this.interrupting.delete(key);
        this.pendingTurnState.delete(key);
        return;
      }
      const listener = this.turnListeners.get(key);
      if (listener) {
        this.turnListeners.delete(key);
        clearTimeout(listener.timer);
        listener.resolve({ threadId, text: listener.text, turn: params.turn });
        return;
      }
      this.bufferPendingState(key, { completed: true, turn: params.turn });
    }
  }

  send(obj) {
    this.ensureSpawned();
    this.child.stdin.write(JSON.stringify(obj) + "\n");
  }

  /** Sends a request to the child and resolves with its `result` (rejects on `error` or child exit). */
  request(method, params) {
    this.ensureSpawned();
    const id = this.nextId++;
    return new Promise((resolve, reject) => {
      this.pending.set(id, { resolve, reject });
      this.send({ jsonrpc: "2.0", id, method, params });
    });
  }

  async ensureInitialized() {
    if (!this.initialized) {
      this.initialized = this.request("initialize", {
        clientInfo: { name: "tycoon-codex-app-server-shim", version: SERVER_VERSION },
      });
    }
    return this.initialized;
  }

  /**
   * Registers a turn listener for `threadId`+`turnId`, times out after
   * `timeoutMs`. Consumes any notification that already arrived and was
   * buffered in pendingTurnState before this call (see the race note on
   * pendingTurnState above) — if that buffer says the turn already
   * completed, resolves immediately instead of registering a listener.
   */
  waitForTurn(threadId, turnId, timeoutMs) {
    const key = AppServerClient.key(threadId, turnId);
    const buffered = this.pendingTurnState.get(key);
    if (buffered) this.pendingTurnState.delete(key);
    if (buffered && buffered.completed) {
      return Promise.resolve({ threadId, text: buffered.text, turn: buffered.turn });
    }
    return new Promise((resolve, reject) => {
      const timer = setTimeout(() => {
        this.turnListeners.delete(key);
        this.interruptTurn(threadId, turnId);
        const err = new Error(`app-server turn timed out after ${timeoutMs}ms (threadId=${threadId}, turnId=${turnId})`);
        err.bridgeTimeout = true;
        reject(err);
      }, timeoutMs);
      this.turnListeners.set(key, { turnId, threadId, text: (buffered && buffered.text) || "", resolve, reject, timer });
    });
  }

  /**
   * Asks the app-server to stop a timed-out turn (`turn/interrupt`), so it
   * stops spending tokens. If no turn/completed follows within the grace period
   * (CODEX_APP_SERVER_INTERRUPT_GRACE_MS, default 5000) the child is killed;
   * it respawns on the next call. Note this also ends any other turn running
   * on the shared child.
   */
  interruptTurn(threadId, turnId) {
    if (!this.child || !turnId) return;
    const key = AppServerClient.key(threadId, turnId);
    const graceRaw = Number(process.env.CODEX_APP_SERVER_INTERRUPT_GRACE_MS);
    const graceMs = Number.isFinite(graceRaw) && graceRaw > 0 ? graceRaw : 5000;
    const grace = setTimeout(() => {
      this.interrupting.delete(key);
      process.stderr.write(`[codex-app-server-mcp] turn ${turnId} did not stop after interrupt; terminating app-server child.\n`);
      this.dispose();
    }, graceMs);
    if (grace.unref) grace.unref();
    this.interrupting.set(key, grace);
    this.request("turn/interrupt", { threadId, turnId }).catch(() => { /* child gone - the grace timer or exit handler cleans up */ });
  }

  clearInterrupts() {
    for (const t of this.interrupting.values()) clearTimeout(t);
    this.interrupting.clear();
  }

  dispose() {
    this.clearInterrupts();
    this.initialized = null;
    if (this.child) {
      try {
        this.child.kill();
      } catch {
        /* best-effort */
      }
      this.child = null;
    }
  }
}

let sharedClient = null;
function getClient() {
  if (!sharedClient) {
    const requestedArgs = process.argv.slice(2);
    const binaryPath = discoverCodexBinary(["app-server"]);
    // Any leading -c key=value pairs (and their values) passed to this shim
    // are forwarded verbatim to the spawned app-server child.
    const extraArgs = requestedArgs;
    sharedClient = new AppServerClient(binaryPath, extraArgs);
  }
  return sharedClient;
}

/** CODEX_APP_SERVER_TIMEOUT_MS first, then the shared TYCOON_BRIDGE_TIMEOUT_MS, else the 600s default. */
function timeoutMs() {
  for (const name of ["CODEX_APP_SERVER_TIMEOUT_MS", "TYCOON_BRIDGE_TIMEOUT_MS"]) {
    const raw = Number(process.env[name]);
    if (process.env[name] && Number.isFinite(raw) && raw > 0) return raw;
  }
  return DEFAULT_TIMEOUT_MS;
}

/** The model an agent asked for, if any (the app-server picks its own default otherwise). */
function requestedModel(args) {
  return args && typeof args.model === "string" ? args.model.trim().replace(/^openai\//i, "") : "";
}

/** Handles the `codex` tool: initialize (once) -> thread/start -> turn/start -> wait for turn/completed. `client` is injectable so tests can point it at a fake app-server script instead of the real discovered binary. */
async function handleCodexTool(args, client) {
  const prompt = args && typeof args.prompt === "string" ? args.prompt : undefined;
  if (!prompt) return isErrorResult("Missing required argument: prompt", "unknown");
  const model = requestedModel(args);

  client = client || getClient();
  try {
    await client.ensureInitialized();
  } catch (err) {
    return isErrorResult(`codex: app-server initialize failed: ${err && err.message ? err.message : String(err)}`, undefined, model);
  }

  const cwd = (args && typeof args.cwd === "string" && args.cwd) || process.cwd();
  let threadResult;
  try {
    threadResult = await client.request("thread/start", model ? { cwd, model } : { cwd });
  } catch (err) {
    return isErrorResult(`codex: thread/start failed: ${err && err.message ? err.message : String(err)}`, undefined, model);
  }
  const threadId = threadResult && threadResult.thread && threadResult.thread.id;
  if (!threadId) return isErrorResult("codex: app-server thread/start returned no thread id", "unknown", model);

  return runTurn(client, threadId, prompt, model);
}

/** Handles the `codex-reply` tool: reuses the caller-supplied thread id, issues another turn/start on it. `client` is injectable for tests, same as handleCodexTool. */
async function handleCodexReplyTool(args, client) {
  const prompt = args && typeof args.prompt === "string" ? args.prompt : undefined;
  if (!prompt) return isErrorResult("Missing required argument: prompt", "unknown");
  const threadId = (args && (args.threadId || args.conversationId)) || undefined;
  if (!threadId) return isErrorResult("codex-reply: missing required argument: threadId (or conversationId)", "unknown");

  client = client || getClient();
  try {
    await client.ensureInitialized();
  } catch (err) {
    return isErrorResult(`codex: app-server initialize failed: ${err && err.message ? err.message : String(err)}`);
  }
  return runTurn(client, threadId, prompt, "");
}

async function runTurn(client, threadId, prompt, model) {
  let turnResult;
  try {
    turnResult = await client.request("turn/start", {
      threadId,
      input: [{ type: "text", text: prompt }],
    });
  } catch (err) {
    return isErrorResult(`codex: turn/start failed: ${err && err.message ? err.message : String(err)}`, undefined, model);
  }
  const turnId = turnResult && turnResult.turn && turnResult.turn.id;

  try {
    const completed = await client.waitForTurn(threadId, turnId, timeoutMs());
    const turn = completed.turn;
    if (turn && (turn.status === "failed" || turn.status === "error")) {
      const detail = turn.error && (turn.error.message || JSON.stringify(turn.error));
      return isErrorResult(`codex: turn ${turn.status}${detail ? ": " + detail : ""}`, undefined, model);
    }
    const result = formatBridgeResult({
      status: "ok",
      provider: PROVIDER,
      model,
      text: completed.text,
      error: { kind: "empty", message: "codex returned an empty answer" },
      extra: { threadId: completed.threadId },
    });
    // outputSchema's `content` mirrors the (capped) summary, never the raw text.
    result.structuredContent.content = result.structuredContent.summary;
    return result;
  } catch (err) {
    const message = `codex: ${err && err.message ? err.message : String(err)}`;
    if (err && err.bridgeTimeout) {
      return formatBridgeResult({ status: "timeout", provider: PROVIDER, model, error: { kind: "timeout", message } });
    }
    return isErrorResult(message, undefined, model);
  }
}

async function handleRequest(msg) {
  const { id, method, params } = msg;

  if (method === "initialize") {
    const clientProtocolVersion = params && typeof params.protocolVersion === "string" ? params.protocolVersion : "2025-06-18";
    respond(id, {
      protocolVersion: clientProtocolVersion,
      capabilities: { tools: {} },
      serverInfo: { name: SERVER_NAME, version: SERVER_VERSION },
    });
    return;
  }

  if (method === "notifications/initialized") return;

  if (method === "tools/list") {
    respond(id, { tools: [CODEX_TOOL, CODEX_REPLY_TOOL] });
    return;
  }

  if (method === "tools/call") {
    const toolName = params && params.name;
    const args = (params && params.arguments) || {};
    try {
      let result;
      if (toolName === "codex") result = await handleCodexTool(args);
      else if (toolName === "codex-reply") result = await handleCodexReplyTool(args);
      else result = isErrorResult(`Unknown tool: ${toolName}`, "unknown");
      respond(id, result);
    } catch (err) {
      respond(id, isErrorResult(`Unexpected error: ${err && err.message ? err.message : String(err)}`));
    }
    return;
  }

  if (id !== undefined) {
    respondError(id, -32601, `Method not found: ${method}`);
  }
}

function main() {
  const rl = readline.createInterface({ input: process.stdin, terminal: false });
  rl.on("line", (line) => {
    const trimmed = line.trim();
    if (!trimmed) return;
    let msg;
    try {
      msg = JSON.parse(trimmed);
    } catch (err) {
      process.stderr.write(`[codex-app-server-mcp] ignoring malformed JSON-RPC line: ${err && err.message ? err.message : String(err)}\n`);
      return;
    }
    handleRequest(msg).catch((err) => {
      process.stderr.write(`[codex-app-server-mcp] unexpected error handling request: ${err && err.message ? err.message : String(err)}\n`);
    });
  });
  rl.on("close", () => {
    if (sharedClient) sharedClient.dispose();
    process.exit(0);
  });
}

